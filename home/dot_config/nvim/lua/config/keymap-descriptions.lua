function M.translate(desc)
  if type(desc) ~= "string" then return desc end
  local known = descriptions[desc] or descriptions[desc:match("^:%s*(.*)$")]
  if known then return known end
  local snippet_key = desc:match("^vim%.snippet%.jump if active, otherwise (.*)$")
  if snippet_key then return "[completion]スニペット内を移動（それ以外は " .. snippet_key .. "）" end
  local commands = desc:match("^blink%.cmp: (.*)$")
  if commands then
    local parts = {}
    for part in commands:gmatch("[^,]+") do
      part = part:match("^%s*(.-)%s*$")
      parts[#parts + 1] = completion[part] or part
    end
    return "[completion]" .. table.concat(parts, "・")
  end
  local action, key = desc:match("^skkelua (%a+) %((.*)%)$")
  if skk[action] then return "[input]" .. skk[action] .. " (" .. key .. ")" end
  return desc
end

function M.picker_transform(item)
  if not item.item then return end
  local translated = M.translate(item.item.desc)
  if translated == item.item.desc then return end
  -- 一覧用のコピーだけを変更し、補完・SKKが識別に使う元のdescを維持する。
  local mapping = {}
  for key, value in pairs(item.item) do mapping[key] = value end
  mapping.desc = translated
  item.item = mapping
  item.text = (item.text or "") .. " " .. translated
end

return M
